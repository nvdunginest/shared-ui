#!/usr/bin/env node
// Measures how much frontend code the document apps duplicate (docs/consolidation-plan.md).
//
//   node scripts/check-duplication.mjs            summary per domain (redundant lines by similarity class)
//   node scripts/check-duplication.mjs --files    + one line per file that exists in >= 2 apps
//   node scripts/check-duplication.mjs --sot      markdown "source of truth" table (newest copy per file)
//   node scripts/check-duplication.mjs --json     machine-readable summary
//
// Apps are looked up next to this repo (../../mini-apps/<name>/frontend); override with APPS_ROOT=/path/to/mini-apps.
// A line counts as redundant when a file with the same relative path exists in more than one app:
// redundant lines = (copies - 1) * lines of the largest copy. Report only: it never fails the build.
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const appsRoot = process.env.APPS_ROOT ?? join(root, "..", "..", "mini-apps");
// Order is the tie-break for "newest": appr first (canonical, decision D3).
const APPS = [
  ["appr", "vpi-adm-appr-final"],
  ["rept", "vpi-adm-rept"],
  ["trip", "vpi-adm-trip"],
  ["idoc", "vpi-adm-idoc"],
  ["odoc", "vpi-adm-odoc"],
];
const EXT = /\.(ts|tsx|css)$/;
const args = new Set(process.argv.slice(2));

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (EXT.test(name)) out.push(p);
  }
  return out;
}

/** path -> { app -> { lines: string[], abs } } */
const byPath = new Map();
for (const [app, dir] of APPS) {
  const base = join(appsRoot, dir, "frontend");
  for (const abs of walk(base)) {
    const rel = relative(base, abs);
    const lines = readFileSync(abs, "utf8").split("\n");
    if (!byPath.has(rel)) byPath.set(rel, {});
    byPath.get(rel)[app] = { lines, abs, repo: join(appsRoot, dir) };
  }
}

/** 2*LCS/(a+b) over lines (same meaning as difflib's ratio, without junk heuristics). */
function ratio(a, b) {
  if (a.length === 0 && b.length === 0) return 1;
  let prev = new Int32Array(b.length + 1);
  let cur = new Int32Array(b.length + 1);
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      cur[j] = a[i - 1] === b[j - 1] ? prev[j - 1] + 1 : Math.max(prev[j], cur[j - 1]);
    }
    [prev, cur] = [cur, prev];
  }
  return (2 * prev[b.length]) / (a.length + b.length);
}

function domain(rel) {
  if (rel.startsWith("platform")) return "platform";
  if (rel.startsWith("external")) return "external/dtaMdms";
  if (rel.startsWith("application/signalR")) return "signalR";
  if (rel.startsWith("application/contexts")) return "app contexts";
  if (rel.startsWith("application/controllers")) return "controllers";
  if (rel.startsWith("application/models") || rel.startsWith("application/enums")) return "models/enums";
  if (rel.startsWith("application/helpers")) return "helpers";
  if (rel.startsWith("presentation/components/Editor")) return "editors";
  if (rel.startsWith("presentation/components")) return "components";
  if (rel.startsWith("presentation/layout")) return "layout/list";
  if (rel.startsWith("presentation/navigation")) return "navigation";
  if (rel.startsWith("presentation/pages/Document")) return "page Document";
  if (rel.startsWith("presentation/pages/Create") || rel.startsWith("presentation/pages/Edit")) return "page Create/Edit";
  if (rel.startsWith("presentation/pages/Home")) return "page Home";
  if (rel.startsWith("presentation/pages")) return "pages other";
  if (rel.startsWith("presentation")) return "theme/styles";
  return "other";
}

const CLASSES = ["identical", "near", "similar", "divergent"];
const classify = (min) => (min === 1 ? "identical" : min >= 0.9 ? "near" : min >= 0.6 ? "similar" : "divergent");

const rows = [];
for (const [rel, copies] of byPath) {
  const apps = Object.keys(copies);
  if (apps.length < 2) continue;
  const base = apps.reduce((a, b) => (copies[b].lines.length > copies[a].lines.length ? b : a));
  const ratios = apps.filter((a) => a !== base).map((a) => ratio(copies[base].lines, copies[a].lines));
  const min = Math.min(...ratios);
  rows.push({ rel, apps, base, min, cls: classify(min), loc: copies[base].lines.length, domain: domain(rel) });
}

function lastCommit(repo, abs) {
  try {
    return execFileSync("git", ["-C", repo, "log", "-1", "--format=%cs", "--", relative(repo, abs)], { encoding: "utf8" }).trim();
  } catch {
    return "";
  }
}

if (args.has("--sot")) {
  const lines = [
    "# Source of truth per duplicated file",
    "",
    "Generated by `npm run check:duplication -- --sot`. Files present in at least two apps with more than one variant.",
    "`newest` = the copy with the latest git commit date (ties go to the first app in the order appr, rept, trip, idoc, odoc).",
    "The `vs newest` column is the line similarity of each other copy against the newest one (100 = identical).",
    "Caveat: the history of `vpi-adm-appr-final` starts at a clean import (2026-10-14), so its dates only mean \"not older than that\"; check `git log` of the other apps before trusting a tie.",
    "",
    "| file | copies | newest | vs newest |",
    "|---|---|---|---|",
  ];
  for (const r of rows.filter((x) => x.cls !== "identical").sort((a, b) => a.rel.localeCompare(b.rel))) {
    const copies = byPath.get(r.rel);
    const dated = r.apps.map((a) => ({ a, d: lastCommit(copies[a].repo, copies[a].abs) }));
    const newest = dated.reduce((x, y) => (y.d > x.d ? y : x));
    const cmp = r.apps
      .filter((a) => a !== newest.a)
      .map((a) => `${a} ${Math.round(ratio(copies[newest.a].lines, copies[a].lines) * 100)}`)
      .join(", ");
    lines.push(`| \`${r.rel}\` | ${r.apps.length} | ${newest.a} (${newest.d || "n/a"}) | ${cmp} |`);
  }
  lines.push("", `Identical in every app that has them (no choice to make): ${rows.filter((x) => x.cls === "identical").length} files.`, "");
  console.log(lines.join("\n"));
  process.exit(0);
}

const summary = {};
for (const r of rows) {
  const s = (summary[r.domain] ??= { identical: 0, near: 0, similar: 0, divergent: 0 });
  s[r.cls] += r.loc * (r.apps.length - 1);
}
const total = Object.fromEntries(CLASSES.map((c) => [c, Object.values(summary).reduce((n, s) => n + s[c], 0)]));

if (args.has("--json")) {
  console.log(JSON.stringify({ apps: APPS.map(([a]) => a), summary, total }, null, 2));
  process.exit(0);
}

const pad = (v, n) => String(v).padStart(n);
console.log(`Apps: ${APPS.map(([a, d]) => `${a}=${d}`).join(" ")}`);
console.log("Redundant lines per domain, by similarity of the copies (identical / near >=90% / similar >=60% / divergent)\n");
console.log(`${"domain".padEnd(18)}${pad("identical", 11)}${pad("near", 8)}${pad("similar", 9)}${pad("divergent", 11)}`);
for (const [d, s] of Object.entries(summary).sort()) {
  console.log(`${d.padEnd(18)}${pad(s.identical, 11)}${pad(s.near, 8)}${pad(s.similar, 9)}${pad(s.divergent, 11)}`);
}
console.log(`${"TOTAL".padEnd(18)}${pad(total.identical, 11)}${pad(total.near, 8)}${pad(total.similar, 9)}${pad(total.divergent, 11)}`);

if (args.has("--files")) {
  console.log("");
  for (const r of rows.sort((a, b) => a.rel.localeCompare(b.rel))) {
    console.log(`${r.cls.padEnd(10)} ${String(r.apps.length)} apps ${pad(r.loc, 5)} loc  ${r.rel}`);
  }
}
